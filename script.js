// ФОРМА БРОНИРОВАНИЯ
const form = document.getElementById('bookingForm');
const msgBox = document.getElementById('formMessage');

form.onsubmit = function(e) {
    e.preventDefault();
    const name = document.getElementById('name').value.trim();
    
    if (!name) {
        msgBox.innerHTML = 'Напишите ваше имя';
        msgBox.style.color = 'red';
        return;
    }
    
    msgBox.innerHTML = 'Спасибо, ' + name + '! Ждём вас в Soulmate!';
    msgBox.style.color = 'green';
    form.reset();
    
    setTimeout(function() {
        msgBox.innerHTML = '';
    }, 5000);
};

// ПЕРЕКЛЮЧЕНИЕ ТЕМЫ С УЧЁТОМ СИСТЕМНОЙ

// Функция применения темы
function applyTheme(theme) {
    if (theme === 'dark') {
        document.body.classList.add('dark-theme');
    } else {
        document.body.classList.remove('dark-theme');
    }
}

// Проверяем, выбирал ли пользователь тему вручную
const savedTheme = localStorage.getItem('theme');

if (savedTheme) {
    // Если пользователь уже выбирал тему — используем её
    applyTheme(savedTheme);
    const themeToggle = document.getElementById('themeToggle');
    if (themeToggle) {
        themeToggle.textContent = savedTheme === 'dark' ? 'Тёмная тема выкл.' : 'Тёмная тема вкл.';
    }
} else {
    // Если пользователь не выбирал — подстраиваемся под систему
    const darkModeMediaQuery = window.matchMedia('(prefers-color-scheme: dark)');
    applyTheme(darkModeMediaQuery.matches ? 'dark' : 'light');
}

// ПЕРЕКЛЮЧЕНИЕ ТЕМЫ
const themeToggle = document.getElementById('themeToggle');

// Проверяем сохранённую тему при загрузке
if (localStorage.getItem('theme') === 'dark') {
    document.body.classList.add('dark-theme');
    themeToggle.textContent = 'Тёмная тема вкл.';
}

// Обработчик клика по кнопке
themeToggle.onclick = function() {
    document.body.classList.toggle('dark-theme');
    
    if (document.body.classList.contains('dark-theme')) {
        localStorage.setItem('theme', 'dark');
        themeToggle.textContent = 'Тёмная тема вкл.';
    } else {
        localStorage.setItem('theme', 'light');
        themeToggle.textContent = 'Тёмная тема выкл.';
    }
};

// Google Calendar URL
const CALENDAR_URL = 'https://script.google.com/macros/s/AKfycbwoCZZW_fj16Q6QnPnXmtZ9bHgvGb_TnZlyVZqOlvC1QmICaMl3kxFdD8TzddM0Y-Gfew/exec';

// Функция отправки в календарь
function sendToCalendar(name, phone, date, time, guests) {
    const data = { name, phone, date, time, guests };
    
    fetch(CALENDAR_URL, {
        method: 'POST',
        mode: 'no-cors',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(data)
    });
}

// Изменяем отправку формы
const formCalendar = document.getElementById('bookingForm');
if (formCalendar) {
    formCalendar.onsubmit = function(e) {
        e.preventDefault();
        
        const name = document.getElementById('name').value.trim();
        const phone = document.getElementById('phone').value.trim();
        const date = document.getElementById('date').value;
        const time = document.getElementById('time').value;
        const guests = document.getElementById('guests').value;
        
        if (!name || !phone) {
            msgBox.innerHTML = 'Заполните имя и телефон!';
            msgBox.style.color = 'red';
            return;
        }
        
        if (!date || !time) {
            msgBox.innerHTML = 'Выберите дату и время!';
            msgBox.style.color = 'red';
            return;
        }
        
        // Отправляем в календарь
        sendToCalendar(name, phone, date, time, guests);
        
        msgBox.innerHTML = 'Спасибо, ' + name + '! Бронь добавлена в календарь. Ждём вас!';
        msgBox.style.color = 'green';
        formCalendar.reset();
        
        setTimeout(() => msgBox.innerHTML = '', 5000);
    };
}
