// ЭЛЕМЕНТЫ МОДАЛЬНОГО ОКНА
const modal = document.getElementById('modal');
const modalPhoto = document.querySelector('.modal-photo');
const modalTitle = document.querySelector('.modal-title');
const modalDesc = document.querySelector('.modal-desc');
const modalDetails = document.querySelector('.modal-details');

// ФУНКЦИЯ ОТКРЫТИЯ
function openModal(title, photo, description, details) {
    if (photo){
        modalPhoto.innerHTML = `<img src="${photo}" class="modal-photo" alt="${title}">`;
    } else{
        modalPhoto.innerHTML = `<div class="modal-emoji">🌿</div>`;
    }
    
    modalTitle.innerHTML = title;
    modalDesc.innerHTML = description;
    modalDetails.innerHTML = details;
    modal.style.display = 'flex';
}

// ФУНКЦИЯ ЗАКРЫТИЯ
function closeModal() {
    modal.style.display = 'none';
}

// КЛИКИ ПО КАРТОЧКАМ
const allCards = document.querySelectorAll('.card');

allCards.forEach(function(card) {
    card.onclick = function() {
        const type = this.getAttribute('data-type');
        const name = this.getAttribute('data-name');
        
        let data = null;
        if (type === 'cat') data = cats[name];
        if (type === 'coffee') data = coffees[name];
        
        if (data) {
            openModal(name, data.photo, data.desc, data.details);
        }
    };
});

